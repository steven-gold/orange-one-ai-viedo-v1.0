function toSimplified(input: string) {
  return PHRASE_REPLACEMENTS.reduce((value, [from, to]) => value.split(from).join(to), input);
}

export function editText(locale: Locale, id: string) {
  const entry = EDIT_CONTROL_TEXT[id];
  if (!entry) return id;
  if (locale === "en") return entry.en;
  if (locale === "zh-CN") return toSimplified(entry.tw);
  return entry.tw;
}

